    private static final Random RANDOM = new Random();

    private QuoteProvider() {
    }

    public static String today() {
        Calendar calendar = Calendar.getInstance();
        int index = (calendar.get(Calendar.YEAR) * 31 + calendar.get(Calendar.DAY_OF_YEAR))
                % QUOTES.length;
        return QUOTES[index];
    }

    public static String random(String exclude) {
        String quote;
        do {
            quote = QUOTES[RANDOM.nextInt(QUOTES.length)];
        } while (quote.equals(exclude));
        return quote;
    }
